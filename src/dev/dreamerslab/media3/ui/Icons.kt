internal class IconDrawable(icon: Icon, color: Int = TEXT_PRIMARY) : Drawable() {
    private val paint = Paint(Paint.ANTI_ALIAS_FLAG).apply { this.color = color }
    private val scaled = Path()
    private var source = PathParser.createPathFromPathData(icon.pathData)

    var icon: Icon = icon
        set(value) {
            if (field == value) return
            field = value
            source = PathParser.createPathFromPathData(value.pathData)
            fit(bounds)
            invalidateSelf()
        }

    var color: Int
        get() = paint.color
        set(value) {
            paint.color = value
            invalidateSelf()
        }

    override fun onBoundsChange(bounds: Rect) = fit(bounds)

    private fun fit(bounds: Rect) {
        val matrix = Matrix().apply {
            setRectToRect(RectF(0f, 0f, 24f, 24f), RectF(bounds), Matrix.ScaleToFit.CENTER)
        }
        source.transform(matrix, scaled)
    }

    override fun draw(canvas: Canvas) {
        canvas.drawPath(scaled, paint)
    }

    override fun setAlpha(alpha: Int) {
        paint.alpha = alpha
    }

    override fun setColorFilter(colorFilter: ColorFilter?) {
        paint.colorFilter = colorFilter
    }

    @Deprecated("Deprecated in Java")
    override fun getOpacity(): Int = PixelFormat.TRANSLUCENT
}
